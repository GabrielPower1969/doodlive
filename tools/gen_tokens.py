#!/usr/bin/env python3
"""tools/design/tokens.json -> web/tokens.css and unity/Assets/DoodLive/Scripts/DesignTokens.cs.
Same idea as gen_i18n.py: one source, both apps generated, both outputs committed."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tok = json.load(open(f"{ROOT}/tools/design/tokens.json", encoding="utf-8"))
kebab = lambda s: "".join("-" + c.lower() if c.isupper() else c for c in s)

css = ["/* GENERATED by tools/gen_tokens.py from tools/design/tokens.json — do not edit by hand. */", ":root {"]
css += [f"  --c-{kebab(k)}: {v};" for k, v in tok["color"].items()]
css += [f"  --s-{kebab(k)}: {v}px;" for k, v in tok["size"].items()]
css += [f"  --f-{kebab(k)}: \"{v}\";" for k, v in tok["font"].items()]
css.append("}")
open(f"{ROOT}/web/tokens.css", "w", encoding="utf-8").write("\n".join(css) + "\n")

def c(h):
    r, g, b = (int(h[i:i + 2], 16) for i in (1, 3, 5))
    return f"new Color32({r}, {g}, {b}, 255)"
cs = ["// GENERATED by tools/gen_tokens.py from tools/design/tokens.json — do not edit by hand.",
      "using UnityEngine;", "", "namespace DoodLive", "{",
      "    /// <summary>Paper & Crayon tokens, same values as web/tokens.css.</summary>",
      "    public static class DesignTokens", "    {"]
cs += [f"        public static readonly Color {k[0].upper() + k[1:]} = {c(v)};" for k, v in tok["color"].items()]
cs += [f"        public const float {k[0].upper() + k[1:]} = {v}f;" for k, v in tok["size"].items()]
cs += ["    }", "}"]
open(f"{ROOT}/unity/Assets/DoodLive/Scripts/DesignTokens.cs", "w", encoding="utf-8").write("\n".join(cs) + "\n")
print(f"{len(tok['color'])} colours, {len(tok['size'])} sizes -> web/tokens.css, unity/.../DesignTokens.cs")
