#!/usr/bin/env python3
"""Fold translations into the repo: tools/i18n/staging/<lang>.json -> tools/i18n/strings.json (UI) and
assets/<story>/i18n.json (story title, blurb, chapter titles, lines), then write the app's story-text table
unity/Assets/DoodLive/Resources/i18n_stories.txt.

    python3 tools/i18n/merge.py            # every staging file present
    python3 tools/i18n/merge.py --table    # only rebuild the Unity table from assets/*/i18n.json

Chinese and English stay where they are (strings.json, timeline.json, stories.json, library.json); i18n.json holds only
the other languages. Staging file shape: {"lang", "ui": {key: text}, "stories": {id: {title, blurb, shots: {id: text},
lines: {id: text}}}}. A missing or empty string is reported and left out (the app falls back to English).
Table format (one entry per line, tab separated, \\n escaped): `<key>\\t<lang>\\t<text>` with keys
`t:<story>` title, `b:<story>` blurb, `s:<story>:<shot>` chapter title, `si:<story>:<n>` the n-th chapter, `l:<story>:<line>` line.
"""
import glob, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
EXTRA = ["fr", "de", "ja", "es", "ar", "pt"]
STAGING = f"{ROOT}/tools/i18n/staging"
TABLE = f"{ROOT}/unity/Assets/DoodLive/Resources/i18n_stories.txt"


def merge():
    sp = f"{ROOT}/tools/i18n/strings.json"
    strings = json.load(open(sp, encoding="utf-8"))
    problems = []
    for lang in EXTRA:
        p = f"{STAGING}/{lang}.json"
        if not os.path.exists(p):
            print(f"{lang}: no staging file"); continue
        tr = json.load(open(p, encoding="utf-8"))
        n_ui = 0
        for k, v in strings.items():
            if k.startswith("_"):
                continue
            t = (tr.get("ui", {}).get(k) or "").strip("‎‏")
            if not t:
                problems.append(f"{lang} ui {k}: missing"); continue
            if t.count("{e}") != v["en"].count("{e}"):
                problems.append(f"{lang} ui {k}: {{e}} count differs"); continue
            v[lang] = t; n_ui += 1
        n_st = 0
        for sid, st in tr.get("stories", {}).items():
            ip = f"{ROOT}/assets/{sid}/i18n.json"
            if not os.path.isdir(f"{ROOT}/assets/{sid}"):
                problems.append(f"{lang} story {sid}: no such story"); continue
            cur = json.load(open(ip, encoding="utf-8")) if os.path.exists(ip) else {"title": {}, "blurb": {}, "shots": {}, "lines": {}}
            if st.get("title"): cur["title"][lang] = st["title"]
            if st.get("blurb"): cur["blurb"][lang] = st["blurb"]
            for kind in ("shots", "lines"):
                for i, t in st.get(kind, {}).items():
                    if t and t.strip():
                        cur[kind].setdefault(i, {})[lang] = t.strip(); n_st += 1
                    else:
                        problems.append(f"{lang} {sid} {kind} {i}: missing")
            json.dump(cur, open(ip, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        print(f"{lang}: {n_ui} ui strings, {n_st} story strings")
    json.dump(strings, open(sp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    open(sp, "a").write("\n")
    for p in problems:
        print("  !", p)


def table():
    rows = []
    for ip in sorted(glob.glob(f"{ROOT}/assets/*/i18n.json")):
        sid = os.path.basename(os.path.dirname(ip))
        d = json.load(open(ip, encoding="utf-8"))
        for lang, t in d.get("title", {}).items(): rows.append((f"t:{sid}", lang, t))
        for lang, t in d.get("blurb", {}).items(): rows.append((f"b:{sid}", lang, t))
        for i, m in d.get("shots", {}).items():
            for lang, t in m.items(): rows.append((f"s:{sid}:{i}", lang, t))
        tlp = f"{ROOT}/assets/{sid}/timeline.json"           # the bookshelf lists chapters by position, not id
        if os.path.exists(tlp):
            for n, sh in enumerate(json.load(open(tlp, encoding="utf-8")).get("shots", [])):
                for lang, t in d.get("shots", {}).get(sh.get("id"), {}).items(): rows.append((f"si:{sid}:{n}", lang, t))
        for i, m in d.get("lines", {}).items():
            for lang, t in m.items(): rows.append((f"l:{sid}:{i}", lang, t))
    esc = lambda s: s.replace("\\", "\\\\").replace("\t", " ").replace("\n", "\\n")
    os.makedirs(os.path.dirname(TABLE), exist_ok=True)
    with open(TABLE, "w", encoding="utf-8") as f:
        f.write("# GENERATED by tools/i18n/merge.py from assets/*/i18n.json — do not edit by hand.\n")
        for k, lang, t in rows:
            f.write(f"{k}\t{lang}\t{esc(t)}\n")
    print(f"{os.path.relpath(TABLE, ROOT)}: {len(rows)} entries")


if __name__ == "__main__":
    if "--table" not in sys.argv:
        merge()
    table()
