#!/usr/bin/env python3
"""tools/i18n/strings.json -> web/i18n.js (ES module) and unity/Assets/DoodLive/Scripts/L10n.cs.
Run after editing strings; both outputs are committed. Keys are shared so the two apps stay word-for-word in sync."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = json.load(open(f"{ROOT}/tools/i18n/strings.json", encoding="utf-8"))
keys = [k for k in data if not k.startswith("_")]

def js_obj(lang):
    return "{\n" + "".join(f"    {k}: {json.dumps(data[k][lang], ensure_ascii=False)},\n" for k in keys) + "  }"
web = f"""// GENERATED by tools/gen_i18n.py from tools/i18n/strings.json — do not edit by hand.
// Pick with ?lang=zh|en, the 中/EN button, or the browser language; remembered in localStorage.
export const STR = {{
  zh: {js_obj('zh')},
  en: {js_obj('en')},
}};
const saved = (() => {{ try {{ return localStorage.getItem('lang'); }} catch {{ return null; }} }})();
const fromUrl = new URLSearchParams(location.search).get('lang');
export let lang = ['zh', 'en'].includes(fromUrl) ? fromUrl : saved || (navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en');
export const t = (key, vars = {{}}) => (STR[lang][key] ?? STR.zh[key] ?? key).replace(/\\{{(\\w+)\\}}/g, (_, k) => vars[k] ?? '');
export const other = key => (STR[lang === 'zh' ? 'en' : 'zh'][key] ?? '');
export function setLang(l) {{ lang = l; try {{ localStorage.setItem('lang', l); }} catch {{}} apply(); }}
export function apply() {{
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  document.title = t('appTitle');
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-lang-toggle]')) el.textContent = lang === 'zh' ? 'EN' : '中';
  document.dispatchEvent(new CustomEvent('langchange', {{ detail: lang }}));
}}
"""
open(f"{ROOT}/web/i18n.js", "w", encoding="utf-8").write(web)

def cs_dict(lang):
    return "".join(f'            {{ "{k}", {json.dumps(data[k][lang], ensure_ascii=False)} }},\n' for k in keys)
cs = f"""// GENERATED by tools/gen_i18n.py from tools/i18n/strings.json — do not edit by hand.
using System.Collections.Generic;
using UnityEngine;

namespace DoodLive
{{
    /// <summary>UI strings (zh / en). L10n.T("key") — same keys as web/i18n.js. Language is remembered in PlayerPrefs,
    /// default from the system language.</summary>
    public static class L10n
    {{
        static readonly Dictionary<string, string> ZH = new Dictionary<string, string>
        {{
{cs_dict('zh')}        }};
        static readonly Dictionary<string, string> EN = new Dictionary<string, string>
        {{
{cs_dict('en')}        }};
        static string lang;
        public static string Lang
        {{
            get
            {{
                if (lang == null) lang = PlayerPrefs.GetString("lang", IsSystemChinese() ? "zh" : "en");
                return lang;
            }}
            set {{ lang = value == "en" ? "en" : "zh"; PlayerPrefs.SetString("lang", lang); }}
        }}
        public static bool IsZh => Lang == "zh";
        public static void Toggle() => Lang = IsZh ? "en" : "zh";
        static bool IsSystemChinese() =>
            Application.systemLanguage == SystemLanguage.Chinese || Application.systemLanguage == SystemLanguage.ChineseSimplified || Application.systemLanguage == SystemLanguage.ChineseTraditional;
        public static string T(string key) => (IsZh ? ZH : EN).TryGetValue(key, out var s) ? s : (ZH.TryGetValue(key, out var z) ? z : key);
        public static string T(string key, string e) => T(key).Replace("{{e}}", e);
        public static string Other(string key) => (IsZh ? EN : ZH).TryGetValue(key, out var s) ? s : "";
    }}
}}
"""
open(f"{ROOT}/unity/Assets/DoodLive/Scripts/L10n.cs", "w", encoding="utf-8").write(cs)
print(f"{len(keys)} keys -> web/i18n.js, unity/.../L10n.cs")
