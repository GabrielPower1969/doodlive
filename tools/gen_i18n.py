#!/usr/bin/env python3
"""tools/i18n/strings.json -> web/i18n.js (ES module) and unity/Assets/DoodLive/Scripts/L10n.cs.
Run after editing strings; both outputs are committed. Keys are shared so the two apps stay word-for-word in sync.
Eight languages (docs/I18N.md). A key missing in a language falls back to English, then Chinese."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = json.load(open(f"{ROOT}/tools/i18n/strings.json", encoding="utf-8"))
keys = [k for k in data if not k.startswith("_")]

LANGS = ["zh", "en", "fr", "de", "ja", "es", "ar", "pt"]          # order of the language picker
NAMES = ["中文", "English", "Français", "Deutsch", "日本語", "Español", "العربية", "Português"]


def val(k, lang):
    return data[k].get(lang) or data[k]["en"]


# ------------------------------------------------------------------------------------------------------------ web
def js_obj(lang):
    return "{\n" + "".join(f"    {k}: {json.dumps(val(k, lang), ensure_ascii=False)},\n" for k in keys) + "  }"


WEB_TAIL = r"""const saved = (() => { try { return localStorage.getItem('lang'); } catch { return null; } })();
const fromUrl = new URLSearchParams(location.search).get('lang');
const nav = (navigator.language || 'en').toLowerCase().slice(0, 2);
export let lang = LANGS.includes(fromUrl) ? fromUrl : LANGS.includes(saved) ? saved : LANGS.includes(nav) ? nav : 'en';
export const t = (key, vars = {}) => (STR[lang][key] ?? STR.en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
export const other = key => (lang === 'zh' ? STR.en : lang === 'en' ? STR.zh : {})[key] ?? '';
export function setLang(l) { lang = l; try { localStorage.setItem('lang', l); } catch {} apply(); }
export function apply() {
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.title = t('appTitle');
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of document.querySelectorAll('[data-lang-toggle]')) el.textContent = lang === 'zh' ? 'EN' : '中';
  document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
}
"""
web = ("// GENERATED by tools/gen_i18n.py from tools/i18n/strings.json — do not edit by hand.\n"
       "// Pick with ?lang=<code>, the language button, or the browser language; remembered in localStorage.\n"
       f"export const LANGS = {json.dumps(LANGS)};\n"
       "export const STR = {\n" + "".join(f"  {l}: {js_obj(l)},\n" for l in LANGS) + "};\n" + WEB_TAIL)
open(f"{ROOT}/web/i18n.js", "w", encoding="utf-8").write(web)


# ------------------------------------------------------------------------------------------------------------ unity
def cs_dict(lang):
    return "".join(f'                {{ "{k}", {json.dumps(val(k, lang), ensure_ascii=False)} }},\n' for k in keys)


CS_TAIL = r"""
        public static readonly string[] Langs = { %LANGS% };
        public static readonly string[] Names = { %NAMES% };
        /// <summary>Raised after the language changes (styles and fonts are rebuilt on it).</summary>
        public static event Action Changed;
        static string lang;
        public static string Lang
        {
            get
            {
                if (lang == null) { var s = PlayerPrefs.GetString("lang", ""); lang = Array.IndexOf(Langs, s) >= 0 ? s : FromSystem(); }
                return lang;
            }
            set
            {
                var v = Array.IndexOf(Langs, value) >= 0 ? value : "en";
                if (v == lang) return;
                lang = v; PlayerPrefs.SetString("lang", lang); PlayerPrefs.Save(); Changed?.Invoke();
            }
        }
        public static bool IsZh => Lang == "zh";
        public static bool IsRtl => Lang == "ar";
        /// <summary>The language shown small under the main one: only the original pair (zh / en) shows its partner.</summary>
        public static string Second => Lang == "zh" ? "en" : Lang == "en" ? "zh" : null;
        /// <summary>"han", "kana", "arabic" or "latin": picks the font.</summary>
        public static string Script(string l) => l == "zh" ? "han" : l == "ja" ? "kana" : l == "ar" ? "arabic" : "latin";
        public static string Script() => Script(Lang);
        public static void Toggle() => Lang = IsZh ? "en" : "zh";
        static string FromSystem()
        {
            switch (Application.systemLanguage)
            {
                case SystemLanguage.Chinese: case SystemLanguage.ChineseSimplified: case SystemLanguage.ChineseTraditional: return "zh";
                case SystemLanguage.French: return "fr";
                case SystemLanguage.German: return "de";
                case SystemLanguage.Japanese: return "ja";
                case SystemLanguage.Spanish: return "es";
                case SystemLanguage.Arabic: return "ar";
                case SystemLanguage.Portuguese: return "pt";
                default: return "en";
            }
        }
        /// <summary>The string in a given language, logical order (no Arabic shaping): English, then Chinese, then the key.</summary>
        public static string In(string l, string key)
        {
            if (l != null && D.TryGetValue(l, out var d) && d.TryGetValue(key, out var s)) return s;
            if (D["en"].TryGetValue(key, out var e)) return e;
            return D["zh"].TryGetValue(key, out var z) ? z : key;
        }
        /// <summary>Text for screen: Arabic is shaped and put in visual order (one line; see ArabicText.Wrap for more).</summary>
        public static string Show(string text) => IsRtl ? ArabicText.Visual(text) : text;
        public static string Raw(string key) => In(Lang, key);
        public static string T(string key) => Show(In(Lang, key));
        public static string T(string key, string e) => Show(In(Lang, key).Replace("{e}", e));
        /// <summary>The same string in the Second language, or "" when there is none.</summary>
        public static string Other(string key) => Second == null ? "" : In(Second, key);
    }
}
"""
cs = ("// GENERATED by tools/gen_i18n.py from tools/i18n/strings.json — do not edit by hand.\n"
      "using System;\nusing System.Collections.Generic;\nusing UnityEngine;\n\n"
      "namespace DoodLive\n{\n"
      "    /// <summary>UI strings in eight languages (docs/I18N.md). L10n.T(\"key\") — same keys as web/i18n.js. The language\n"
      "    /// is remembered in PlayerPrefs; the default comes from the system language, else English.</summary>\n"
      "    public static class L10n\n    {\n"
      "        static readonly Dictionary<string, Dictionary<string, string>> D = new Dictionary<string, Dictionary<string, string>>\n        {\n"
      + "".join(f'            {{ "{l}", new Dictionary<string, string>\n            {{\n{cs_dict(l)}            }} }},\n' for l in LANGS)
      + "        };"
      + CS_TAIL.replace("%LANGS%", ", ".join(json.dumps(l) for l in LANGS))
               .replace("%NAMES%", ", ".join(json.dumps(n, ensure_ascii=False) for n in NAMES)))
open(f"{ROOT}/unity/Assets/DoodLive/Scripts/L10n.cs", "w", encoding="utf-8").write(cs)
print(f"{len(keys)} keys x {len(LANGS)} languages -> web/i18n.js, unity/.../L10n.cs")
